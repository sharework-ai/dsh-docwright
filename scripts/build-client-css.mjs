#!/usr/bin/env node
// Compile the client's Tailwind source (src/client/styles.css) to minified
// CSS and emit src/client/generated-css.ts — the string constant the bundle
// imports and injects as <style data-plugin-css="docwright/client.css">
// (see index.tsx). Part of build:client and typecheck; never hand-edited.
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import { dirname, join } from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const pkgDir = dirname(require.resolve('@tailwindcss/cli/package.json'))
const bin = JSON.parse(fs.readFileSync(join(pkgDir, 'package.json'), 'utf8')).bin
const cliPath = join(pkgDir, typeof bin === 'string' ? bin : bin.tailwindcss ?? Object.values(bin)[0])

fs.mkdirSync('client', { recursive: true })
execFileSync(process.execPath, [cliPath, '-i', 'src/client/styles.css', '-o', 'client/client.css', '--minify'], { stdio: 'inherit' })
const css = fs.readFileSync('client/client.css', 'utf8').trim()
if (css.length === 0) throw new Error('compiled client CSS is empty — check src/client/styles.css')
fs.writeFileSync('src/client/generated-css.ts', `/** GENERATED by scripts/build-client-css.mjs from src/client/styles.css — do not edit. */
export const CLIENT_CSS_BUNDLE = ${JSON.stringify(css)}
`)
console.log(`client CSS compiled (${css.length} bytes)`)
